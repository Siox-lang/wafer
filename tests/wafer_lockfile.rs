//! Exercise Cargo's actual resolver, Git implementation and lockfile encoder.

use cargo_test_support::{cargo_test, git};
use std::{
    net::TcpListener,
    path::Path,
    process::{Command, Output},
};

const WAFER: &str = env!("CARGO_BIN_EXE_wafer");
const CARGO: &str = env!("CARGO_BIN_EXE_cargo");

fn write(root: &Path, path: &str, value: &str) {
    let path = root.join(path);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, value).unwrap();
}

fn cli(binary: &str, root: &Path, args: &[&str]) -> Output {
    Command::new(binary)
        .current_dir(root)
        .env_clear()
        .env("HOME", root.join("home"))
        .env("WAFER_HOME", root.join("home/.wafer"))
        .env("CARGO_HOME", root.join("home/.cargo"))
        .env("RUSTC", "must-not-run-rustc")
        .env("SIOXC", "must-not-run-sioxc")
        .args(args)
        .output()
        .unwrap()
}

fn success(output: Output) {
    assert!(
        output.status.success(),
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn lock(root: &Path, name: &str) -> String {
    std::fs::read_to_string(root.join(name)).unwrap()
}

#[cargo_test]
fn cargo_and_wafer_lock_the_same_path_graph_in_separate_files() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    for manifest in ["Cargo.toml", "Wafer.toml"] {
        write(
            root,
            manifest,
            "[package]\nname='controller'\nversion='1.0.0'\n[dependencies]\ndep={path='dep',version='1'}\n",
        );
        write(
            root,
            &format!("dep/{manifest}"),
            "[package]\nname='dep'\nversion='1.2.3'\n[lib]\nname='vendor'\n",
        );
    }
    for source in [
        "src/lib.siox",
        "src/lib.rs",
        "dep/src/lib.siox",
        "dep/src/lib.rs",
    ] {
        write(root, source, "metadata must not compile this");
    }
    success(cli(CARGO, root, &["generate-lockfile", "--offline"]));
    let cargo = lock(root, "Cargo.lock");
    success(cli(WAFER, root, &["generate-lockfile", "--offline"]));
    let wafer = lock(root, "Wafer.lock");
    assert_eq!(
        cargo.replacen("@generated by Cargo", "@generated by Wafer", 1),
        wafer
    );
    assert_eq!(lock(root, "Cargo.lock"), cargo);
    assert!(wafer.contains("name = \"dep\"") && wafer.contains("version = \"1.2.3\""));
    success(cli(WAFER, root, &["generate-lockfile", "--frozen"]));
    assert_eq!(lock(root, "Wafer.lock"), wafer);
    assert!(!root.join("target").exists());
}

#[cargo_test]
fn wafer_locked_failures_preserve_both_lockfiles_and_ignore_rust_version_preferences() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(root, "Cargo.lock", "unrelated Rust project data\n");
    write(
        root,
        "Wafer.toml",
        "[package]\nname='controller'\nversion='1.0.0'\nresolver='3'\n",
    );
    write(root, "src/lib.siox", "metadata only");
    let missing = cli(WAFER, root, &["generate-lockfile", "--locked"]);
    assert!(!missing.status.success());
    assert!(String::from_utf8_lossy(&missing.stderr).contains("Wafer.lock"));
    assert!(!root.join("Wafer.lock").exists());
    success(cli(WAFER, root, &["generate-lockfile", "--offline"]));
    let original = lock(root, "Wafer.lock");
    write(
        root,
        "Wafer.toml",
        "[package]\nname='controller'\nversion='2.0.0'\nresolver='3'\n",
    );
    let changed = cli(WAFER, root, &["generate-lockfile", "--locked"]);
    assert!(!changed.status.success());
    assert_eq!(lock(root, "Wafer.lock"), original);
    assert_eq!(lock(root, "Cargo.lock"), "unrelated Rust project data\n");
    assert!(!root.join("target").exists());
}

#[cargo_test]
fn wafer_git_discovery_uses_nested_wafer_manifests_and_pins_the_real_commit() {
    let dir = tempfile::tempdir().unwrap();
    let repo = git::repo(&dir.path().join("source"))
        .file("Wafer.toml", "[workspace]\nmembers=['packages/*']\n[workspace.package]\nversion='1.2.3'\n")
        .file("packages/dep/Wafer.toml", "[package]\nname='dep'\nversion.workspace=true\n[dependencies]\nleaf={path='../leaf'}\n")
        .file("packages/dep/src/lib.siox", "metadata only")
        .file("packages/leaf/Wafer.toml", "[package]\nname='leaf'\nversion.workspace=true\n")
        .file("packages/leaf/src/lib.siox", "metadata only")
        .file("packages/leaf/Cargo.toml", "[broken Rust manifest")
        .build();
    let root = dir.path().join("project");
    write(
        &root,
        "Wafer.toml",
        &format!(
            "[package]\nname='controller'\nversion='0.1.0'\n[dependencies]\ndep={{git={:?},rev={:?}}}\n",
            repo.url().as_str(),
            repo.revparse_head()
        ),
    );
    write(&root, "src/lib.siox", "metadata only");
    success(cli(WAFER, &root, &["generate-lockfile"]));
    let wafer = lock(&root, "Wafer.lock");
    assert!(
        wafer.contains(&format!("#{}", repo.revparse_head())),
        "{wafer}"
    );
    for name in ["dep", "leaf"] {
        assert!(wafer.contains(&format!("name = \"{name}\"")), "{wafer}");
    }
    success(cli(
        WAFER,
        &root,
        &["generate-lockfile", "--offline", "--locked"],
    ));
    assert_eq!(lock(&root, "Wafer.lock"), wafer);
    assert!(!root.join("Cargo.lock").exists());
}

#[cargo_test]
fn wafer_git_offline_cache_survives_an_unavailable_source_and_explicit_regeneration_moves_refs() {
    let dir = tempfile::tempdir().unwrap();
    let repo = git::repo(&dir.path().join("source"))
        .file("Wafer.toml", "[package]\nname='dep'\nversion='1.0.0'\n")
        .file("src/lib.siox", "first source")
        .build();
    let source = repo.root().to_path_buf();
    let original_commit = repo.revparse_head();
    let root = dir.path().join("project");
    write(
        &root,
        "Wafer.toml",
        &format!(
            "[package]\nname='controller'\nversion='0.1.0'\n[dependencies]\ndep={{git={:?}}}\n",
            repo.url().as_str()
        ),
    );
    write(&root, "src/lib.siox", "metadata only");
    success(cli(WAFER, &root, &["generate-lockfile"]));
    let original = lock(&root, "Wafer.lock");
    assert!(original.contains(&original_commit));
    drop(repo);
    std::fs::rename(&source, dir.path().join("unavailable-source")).unwrap();
    success(cli(WAFER, &root, &["generate-lockfile", "--offline"]));
    assert_eq!(lock(&root, "Wafer.lock"), original);
    std::fs::rename(dir.path().join("unavailable-source"), &source).unwrap();
    let repo = git2::Repository::open(&source).unwrap();
    write(&source, "src/lib.siox", "second source");
    git::add(&repo);
    let changed_commit = git::commit(&repo).to_string();
    assert_ne!(changed_commit, original_commit);
    success(cli(WAFER, &root, &["generate-lockfile"]));
    let updated = lock(&root, "Wafer.lock");
    assert!(updated.contains(&changed_commit) && !updated.contains(&original_commit));
}

#[cargo_test]
fn wafer_registry_dependencies_and_replacements_fail_before_any_connection() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    listener.set_nonblocking(true).unwrap();
    let index = format!("sparse+http://{}/", listener.local_addr().unwrap());
    write(
        root,
        ".wafer/config.toml",
        &format!(
            "[http]\ntimeout=1\n[net]\nretry=0\n[source.crates-io]\nreplace-with='mirror'\n[source.mirror]\nregistry={index:?}\n"
        ),
    );
    write(root, "src/lib.siox", "metadata only");
    for dependency in [
        "[dependencies]\nmissing='1'\n",
        "[dependencies]\nmissing={version='1',optional=true}\n",
        "[dependencies]\ndep={path='dep'}\n",
    ] {
        write(
            root,
            "Wafer.toml",
            &format!("[package]\nname='controller'\nversion='0.1.0'\n{dependency}"),
        );
        write(
            root,
            "dep/Wafer.toml",
            "[package]\nname='dep'\nversion='1.0.0'\n[dependencies]\nmissing='1'\n",
        );
        write(root, "dep/src/lib.siox", "metadata only");
        let output = cli(WAFER, root, &["generate-lockfile"]);
        assert!(
            !output.status.success(),
            "{dependency}: {}",
            String::from_utf8_lossy(&output.stdout)
        );
        assert!(
            String::from_utf8_lossy(&output.stderr)
                .contains("registry/source adapter is not implemented"),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(!root.join("Wafer.lock").exists());
        assert!(
            matches!(listener.accept(), Err(error) if error.kind() == std::io::ErrorKind::WouldBlock)
        );
    }
    write(
        root,
        "dep/Wafer.toml",
        "[package]\nname='dep'\nversion='1.0.0'\n[dependencies]\nmissing={version='1',optional=true}\n",
    );
    success(cli(WAFER, root, &["generate-lockfile"]));
    assert!(!lock(root, "Wafer.lock").contains("name = \"missing\""));
    assert!(
        matches!(listener.accept(), Err(error) if error.kind() == std::io::ErrorKind::WouldBlock)
    );
}

#[cargo_test]
fn invalid_path_versions_and_cycles_are_reported_without_writing_a_lock() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(root, "src/lib.siox", "metadata only");
    write(root, "dep/src/lib.siox", "metadata only");
    write(
        root,
        "Wafer.toml",
        "[package]\nname='controller'\nversion='1.0.0'\n[dependencies]\ndep={path='dep',version='2'}\n",
    );
    write(
        root,
        "dep/Wafer.toml",
        "[package]\nname='dep'\nversion='1.0.0'\n",
    );
    let output = cli(WAFER, root, &["generate-lockfile", "--offline"]);
    assert!(!output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("version"));
    assert!(!root.join("Wafer.lock").exists());
    write(
        root,
        "Wafer.toml",
        "[package]\nname='controller'\nversion='1.0.0'\n[dependencies]\ndep={path='dep'}\n",
    );
    write(
        root,
        "dep/Wafer.toml",
        "[package]\nname='dep'\nversion='1.0.0'\n[dependencies]\ncontroller={path='..'}\n",
    );
    let output = cli(WAFER, root, &["generate-lockfile", "--offline"]);
    assert!(!output.status.success());
    assert!(
        String::from_utf8_lossy(&output.stderr).contains("cyclic package dependency"),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(!root.join("Wafer.lock").exists());
}
